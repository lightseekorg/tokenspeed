# decode
@dataclasses.dataclass
class TransferInfo:
    """One request manifest associated with a registered Decode session."""

    room: int
    mooncake_session_id: str
    block_manifest: CachePDBlockManifest | None = None

    @property
    def is_dummy(self) -> bool:
        return self.block_manifest is None

    @staticmethod
    def route_header_from_zmq(msg: list[bytes]) -> tuple[int, str]:
        if not isinstance(msg, list) or len(msg) != 3:
            raise ValueError("CachePD pre-allocation requires exactly 3 frames")
        room = _bounded_ascii_uint(
            msg[0], name="CachePD room", minimum=0, maximum=(1 << 63) - 1
        )
        session_id = msg[1].decode("ascii")
        if not session_id or len(session_id) > 512:
            raise ValueError("CachePD request requires a Decode session")
        return room, session_id

    @classmethod
    def from_zmq(cls, msg: list[bytes]):
        room, session_id = cls.route_header_from_zmq(msg)
        block_manifest = (
            CachePDBlockManifest.from_wire_bytes(msg[2]) if msg[2] else None
        )
        return cls(
            room=room,
            mooncake_session_id=session_id,
            block_manifest=block_manifest,
        )


# decode
@dataclasses.dataclass(frozen=True)
class KVArgsRegisterInfo:
    endpoint: str
    dst_port: int
    mooncake_session_id: str
    dst_kv_ptr: int
    peer_cache_layout: CacheTransferContract
    decode_tp_size: int
    decode_tp_rank: int
    # Computed once by the receiving Prefill rank from the typed registration.
    transfer_fragments: tuple[CacheTransferFragment, ...] = ()
    is_dummy: bool = False
    expected_decode_ranks: frozenset[int] = frozenset()

    @staticmethod
    def route_header_from_zmq(msg: list[bytes]) -> tuple[str, int, str]:
        """Parse the reply route even when the typed layout is later rejected."""
        if len(msg) != 8 or msg[0] != b"None":
            raise ValueError("CachePD slab registration requires exactly 8 frames")
        endpoint = msg[1].decode("ascii")
        session_id = msg[3].decode("ascii")
        if not endpoint or len(endpoint) > 255:
            raise ValueError("CachePD registration endpoint is invalid")
        if not session_id or len(session_id) > 512:
            raise ValueError("CachePD registration session is invalid")
        dst_port = _bounded_ascii_uint(
            msg[2], name="CachePD registration port", minimum=1, maximum=65535
        )
        return endpoint, dst_port, session_id

    @classmethod
    def from_zmq(cls, msg: list[bytes]):
        endpoint, dst_port, session_id = cls.route_header_from_zmq(msg)
        if len(msg[4]) != 8:
            raise ValueError("CachePD slab pointer frame must be exactly 8 bytes")
        peer_cache_layout = CacheTransferContract.from_wire_bytes(msg[5])
        decode_tp_size = _bounded_ascii_uint(
            msg[6],
            name="CachePD decode_tp_size",
            minimum=1,
            maximum=MAX_CACHE_TP_SIZE,
        )
        decode_tp_rank = _bounded_ascii_uint(
            msg[7],
            name="CachePD decode_tp_rank",
            minimum=0,
            maximum=decode_tp_size - 1,
        )
        dst_kv_ptr = struct.unpack("Q", msg[4])[0]
        if dst_kv_ptr == 0:
            raise ValueError("CachePD slab pointer must be nonzero")
        return cls(
            endpoint=endpoint,
            dst_port=dst_port,
            mooncake_session_id=session_id,
            dst_kv_ptr=dst_kv_ptr,
            peer_cache_layout=peer_cache_layout,
            decode_tp_size=decode_tp_size,
            decode_tp_rank=decode_tp_rank,
        )


