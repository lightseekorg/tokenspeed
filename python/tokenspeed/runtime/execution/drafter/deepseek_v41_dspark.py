"""DeepSeek V4.1 checkpoint-local DSpark drafter over LCM-owned windows.

Every stage's context window is a field of the target's SWA cache group, so
the drafter holds no per-request state: rows are written at the target's SWA
slots for the very rows the target's decoder just processed -- the backend's
``decoder_view()``, each prompt's last window plus the decode rows, which is
also the layout of the captured taps -- and the block draft reads the 128
positions before its anchor through the backend's slot resolver. Prefix hits
(the SWA group is regenerated by bounded replay, these rows with it), PD
transfer and L2 therefore carry the draft state with the KV.
"""

