class DeepseekV41DSpark(BaseDrafter):
    """V4.1 DSpark block drafter whose windows live in the SWA cache group."""

    supports_dp_local_graph: bool = True
    shares_target_embed_head = True
    supports_speculative_sampling = True

    def __init__(
        self,
        spec_num_tokens: int,
        spec_num_steps: int,
        draft_model_runner: ModelRunner,
        attn_backend,
        token_to_kv_pool,
        runtime_states: RuntimeStates | None,
        input_buffers: InputBuffers,
        vocab_size: int,
    ) -> None:
        super().__init__(
            spec_num_tokens=spec_num_tokens,
            spec_num_steps=spec_num_steps,
            draft_model_runner=draft_model_runner,
            runtime_states=runtime_states,
            input_buffers=input_buffers,
            attn_backend=attn_backend,
            token_to_kv_pool=token_to_kv_pool,
            vocab_size=vocab_size,
        )
        self.device = torch.device(draft_model_runner.device)
        self.draft_model = draft_model_runner.model
        self.model = self.draft_model.model
        # Bound by wire_target.
        self.target_model: torch.nn.Module | None = None
        self.lm_head: torch.nn.Module | None = None
        self.tp_group: tuple[int, ...] | None = None
        self.block_size = int(self.model.block_size)
        validate_block_widths(
            "DSPARK", self.block_size, spec_num_steps, spec_num_tokens
        )
        self.target_layer_ids = list(self.model.target_layer_ids)
        self.hidden_width = len(self.target_layer_ids) * int(self.model.hidden_size)
        max_bs = int(self.input_buffers.max_bs)
        self.next_tokens_buf = torch.empty(
            (max_bs, self.spec_num_tokens), dtype=torch.int32, device=self.device
        )
        self.start_pos_buf = torch.empty(
            (max_bs,), dtype=torch.int64, device=self.device
        )
        self.candidates, self.partials = dspark_greedy_workspace(
            int(self.draft_model.mapping.attn.tp_size),
            max_bs,
            int(self.model.markov_projection.num_embeddings_per_partition),
            self.device,
        )

        self.adaptive_min_batch_size = global_server_args_dict[
            "dsv41_dspark_min_batch_size"
        ]
        self.verify_graph_token_step: int | None = None
        self._verify_calibrations: tuple[VerifyCalibration, ...] = ()
        self._verify_policy_ms: float | None = None
        self._verify_budget_counts: dict[tuple[int, int, str], int] = {}
        self._verify_budget_context_bounds: tuple[int, int] | None = None
        self.verify_budget_policy: VerifyBudgetPolicy | None = None
        if global_server_args_dict["enable_dsv41_adaptive_dspark"]:
            self.verify_budget_policy = VerifyBudgetPolicy(
                enabled=True,
                min_batch_size=self.adaptive_min_batch_size,
                verify_width=self.spec_num_tokens,
                min_gain=0.02,
            )
            self.verify_graph_token_step = 16
        self.verify_feedback = (
            VerifyFeedback(draft_width=self.block_size)
            if self.verify_budget_policy is not None
            else None
        )
        self._verify_budget_buffers: dict[int, _VerifyBudgetBuffers] = {}
        self._verify_budget_graphs: dict[tuple[int, int], torch.cuda.CUDAGraph] = {}
        self._pending_verify_feedback: list[_PendingVerifyFeedback] = []
        self._verify_cache_initialized = False
        self._verify_cache: VerifyCalibrationCache | None = None
        self._cached_verify_profiles: tuple[VerifyCalibration, ...] = ()
        self.confidence_scores: torch.Tensor | None = None
        self.confidence_features: torch.Tensor | None = None
        self._confidence_admission_ids: list[int | None] = []
        self._verify_candidates: torch.Tensor | None = None
        self._graph_query_tokens: int | None = None
        self._sample_proposals: Callable | None = None
        self._verify_layout_counts: tuple[int, ...] | None = None
        self._verify_rows: torch.Tensor | None = None
        self._verify_indptr: torch.Tensor | None = None
        if self.verify_budget_policy is not None:
            if runtime_states is None:
                raise ValueError("adaptive V4.1 DSpark requires runtime request state")
            slots = runtime_states.future_input_map.shape[0]
            self.confidence_scores = torch.full(
                (slots, self.block_size),
                float("inf"),
                dtype=torch.float32,
                device=self.device,
            )
            self._confidence_admission_ids = [None] * slots
            # Stable storage: a captured packed forward reads these same
            # addresses even when the next batch has different query boundaries.
            self._verify_rows = torch.empty(
                max_bs * self.spec_num_tokens, dtype=torch.int64, device=self.device
            )
            self._verify_indptr = torch.empty(
                max_bs + 1, dtype=torch.int64, device=self.device
            )
            self.confidence_features = torch.empty(
                max_bs,
                self.block_size,
                self.model.hidden_size,
                # Norm weights can be FP32 while the draft activations are BF16.
                dtype=self.model.embed_tokens.weight.dtype,
                device=self.device,
            )

    def slot_state_rows(self, slot: int) -> list[torch.Tensor]:
        return [] if self.confidence_scores is None else [self.confidence_scores[slot]]

    def configure_decode_graph_scope(self, *, local: bool) -> None:
        if local:
            from tokenspeed.runtime.models.deepseek_v41 import DeepseekV41ForCausalLM

            if self.target_model is None:
                raise ValueError("local DP graphs require the wired target model")
            if not isinstance(self.target_model, DeepseekV41ForCausalLM):
                raise ValueError("local DP graphs require the native V4.1 target model")
            for model in (self.target_model, self.draft_model):
                mapping = model.mapping
                if (
                    mapping.attn.tp_size != 1
                    or mapping.dense.tp_size != 1
                    or mapping.moe.tp_size != 1
                    or mapping.lm_head.tp_size != 1
                    or not all(layer.ffn.use_mega_moe for layer in model.model.layers)
                ):
                    raise ValueError(
                        "local DP graphs require target and draft MegaMoE with TP1"
                    )
        super().configure_decode_graph_scope(local=local)

    def bind_sampling_backend(self, sampling_backend) -> None:
        if self.runtime_states is None or self.runtime_states.draft_probs is None:
            return
        from tokenspeed.runtime.sampling.backends.flashinfer import (
            FlashInferSamplingBackend,
        )

        if (
            self.verify_budget_policy is None
            or self.draft_model.mapping.attn.tp_size != 1
            or not isinstance(sampling_backend, FlashInferSamplingBackend)
        ):
            raise ValueError(
                "sampled V4.1 DSpark requires adaptive flashinfer verification "
                "and attention TP1"
            )
        self._sample_proposals = sampling_backend.sample_dspark_proposals

    def export_slot_state(self, slot, out, stream, *, admission_id: int) -> None:
        if (
            self.confidence_scores is not None
            and self._confidence_admission_ids[slot] != admission_id
        ):
            from tokenspeed.runtime.execution.slot_state import pack_slot_rows

            pack_slot_rows(
                [torch.full_like(self.confidence_scores[slot], float("inf"))],
                out,
                stream,
            )
        else:
            super().export_slot_state(slot, out, stream, admission_id=admission_id)

    def import_slot_state(self, slot, src, stream, *, admission_id: int) -> None:
        super().import_slot_state(slot, src, stream, admission_id=admission_id)
        if self.verify_feedback is not None:
            self.verify_feedback.invalidate()
        if self.confidence_scores is not None:
            self._confidence_admission_ids[slot] = admission_id

    def on_target_weights_updated(self) -> None:
        # A hot reload must not reuse or overwrite the boot checkpoint's costs.
        self._verify_cache = None
        self._cached_verify_profiles = ()
        self._verify_cache_initialized = True
        self._verify_calibrations = ()
        if self.verify_feedback is not None:
            self.verify_feedback.invalidate()
        if self.confidence_scores is not None:
            self.confidence_scores.fill_(float("inf"))

    def verify_candidates(self) -> torch.Tensor:
        if self._verify_candidates is None:
            raise RuntimeError("packed verification has no original candidate window")
        return self._verify_candidates

    def pack_grammar_vocab_mask(
        self, vocab_mask: torch.Tensor, *, num_tokens: int
    ) -> torch.Tensor:
        """Gather request-major grammar rows into the packed target layout."""
        if self._verify_rows is None:
            raise RuntimeError("adaptive verification is disabled")
        return vocab_mask.index_select(0, self._verify_rows[:num_tokens])

    def decode_graph_query_capacities(self, bs: int) -> tuple[int, ...]:
        if (
            bs < self.adaptive_min_batch_size
            or bs * self.spec_num_tokens > dsv41.VERIFY_LAYOUT_MAX_TOKENS
        ):
            return (bs * self.spec_num_tokens,)
        if self.confidence_scores is None or self.verify_graph_token_step is None:
            return super().decode_graph_query_capacities(bs)
        step = min(bs, self.verify_graph_token_step)
        full = bs * self.spec_num_tokens
        return tuple(dict.fromkeys((*range(bs, full, step), full)))

    def prepare_decode_graph_token_capture_layout(
        self, *, bs: int, query_tokens: int
    ) -> None:
        if (
            self.confidence_scores is None
            or self.verify_graph_token_step is None
            or bs * self.spec_num_tokens > dsv41.VERIFY_LAYOUT_MAX_TOKENS
        ):
            return super().prepare_decode_graph_token_capture_layout(
                bs=bs, query_tokens=query_tokens
            )
        width, extra = divmod(query_tokens, bs)
        counts = (width + 1,) * extra + (width,) * (bs - extra)
        self.prepare_verify_layout(counts, num_tokens=query_tokens)

    def prepare_decode_graph_token_layout(
        self, ctx: ForwardContext, *, actual_bs: int, padded_bs: int
    ) -> int:
        if (
            self.draft_model.mapping.attn.dp_size > 1
            and ctx.global_bs != ctx.global_num_decodes
        ):
            return padded_bs * self.spec_num_tokens
        return self._prepare_verify_budget(
            actual_bs=actual_bs, padded_bs=padded_bs, rank_sizes=ctx.global_bs
        )

    def _prepare_verify_budget(
        self, *, actual_bs: int, padded_bs: int, rank_sizes: list[int] | None
    ) -> int:
        """Use the same host policy and agreement for serving and startup costs."""
        full = padded_bs * self.spec_num_tokens
        if self.verify_budget_policy is None:
            return full
        if self.dp_local_graph:
            return self._prepare_calibrated_budget(
                actual_bs=actual_bs, padded_bs=padded_bs
            )
        if self.draft_model.mapping.attn.dp_size > 1:
            # Admission must use global metadata before entering collectives.
            # Pure decode peers share physical capacity, not actual occupancy.
            if (
                rank_sizes is None
                or len(rank_sizes) != len(self._verification_group)
                or any(n < 0 or n > padded_bs for n in rank_sizes)
                or max(rank_sizes) < self.adaptive_min_batch_size
                or padded_bs not in self._verify_budget_buffers
            ):
                return full
            self._poll_verify_feedback()
            return self._prepare_dp_verify_budget(
                batch_size=padded_bs, actual_bs=actual_bs, rank_sizes=rank_sizes
            )
        if not self.verify_budget_policy.admits(
            batch_size=actual_bs, graph_batch_size=padded_bs
        ):
            return full
        return self._prepare_calibrated_budget(actual_bs=actual_bs, padded_bs=padded_bs)

    def set_decode_graph_query_extent(self, num_tokens: int | None) -> None:
        self._graph_query_tokens = (
            num_tokens if self.confidence_scores is not None else None
        )

    def prepare_verify_layout(
        self, counts: tuple[int, ...], *, num_tokens: int
    ) -> None:
        """Publish row indices and CSR in place before a packed forward.

        num_tokens is the physical query extent, including graph padding.
        Padded rows read harmless input row zero; attention masks them using CSR.
        """
        if self._verify_rows is None or self._verify_indptr is None:
            raise RuntimeError("adaptive verification is disabled")
        if not counts or len(counts) + 1 > self._verify_indptr.numel():
            raise ValueError("invalid verification batch size")
        if any(n < 1 or n > self.spec_num_tokens for n in counts):
            raise ValueError(
                "verification counts must include an anchor and fit the draft"
            )
        if not sum(counts) <= num_tokens <= len(counts) * self.spec_num_tokens:
            raise ValueError(
                "physical verification extent does not cover the live rows"
            )
        if counts != self._verify_layout_counts:
            rows = [
                r * self.spec_num_tokens + c
                for r, n in enumerate(counts)
                for c in range(n)
            ]
            starts = [0]
            for n in counts:
                starts.append(starts[-1] + n)
            self._verify_rows.zero_()
            self._verify_rows[: len(rows)].copy_(
                torch.tensor(rows, dtype=torch.int64, device=self.device)
            )
            self._verify_indptr[: len(starts)].copy_(
                torch.tensor(starts, dtype=torch.int64, device=self.device)
            )
            self._verify_layout_counts = counts

    @contextmanager
    def packed_target_forward_context(self, ctx: ForwardContext, *, num_tokens: int):
        """Graph-capturable packing/restoration with previously published CSR."""
        if self._verify_rows is None or self._verify_indptr is None:
            raise RuntimeError("adaptive verification is disabled")
        ib = self.input_buffers
        original = ctx.bs * self.spec_num_tokens
        snapshots = []
        original_global_num_tokens = ctx.global_num_tokens
        ctx.decode_query_indptr = self._verify_indptr[: ctx.bs + 1]
        try:
            for view in (
                ib.input_ids_buf[:original],
                ib.positions_buf[:original],
                *ib.ngram_model_kwargs(original).values(),
            ):
                saved = view.clone()
                snapshots.append((view, saved))
                if len(snapshots) == 1:
                    self._verify_candidates = saved.reshape(
                        ctx.bs, self.spec_num_tokens
                    )
                view[:num_tokens].copy_(
                    saved.index_select(0, self._verify_rows[:num_tokens])
                )
            ctx.input_num_tokens = num_tokens
            if self.dp_local_graph:
                # MegaMoE consumes local rows from a fixed-capacity symmetric
                # buffer; peer physical extents are not captured host metadata.
                ctx.global_num_tokens = None
            elif original_global_num_tokens is not None:
                ctx.global_num_tokens = [num_tokens] * len(original_global_num_tokens)
            backend = ctx.attn_backend
            tables = backend.query_metadata(ForwardMode.DECODE).block_tables
            backend.refresh_decode_metadata(
                ctx.bs,
                ctx.bs,
                ib.req_pool_indices_buf[: ctx.bs],
                ib.seq_lens_buf[: ctx.bs],
                forward_mode=ForwardMode.DECODE,
                block_tables=tables,
                num_tokens=num_tokens,
                decode_query_indptr=ctx.decode_query_indptr,
                for_graph_replay=torch.cuda.is_current_stream_capturing(),
            )
            yield
        finally:
            # Sampling and NaN checks still consume packed target rows; keep
            # input_num_tokens packed while restoring borrowed input storage.
            ctx.global_num_tokens = original_global_num_tokens
            for view, saved in snapshots:
                view.copy_(saved)

    @contextmanager
    def target_forward_context(self, ctx: ForwardContext):
        self._verify_candidates = None
        if self._graph_query_tokens is not None and ctx.num_extends == 0:
            if self._graph_query_tokens == ctx.bs * self.spec_num_tokens:
                yield
                return
            with self.packed_target_forward_context(
                ctx, num_tokens=self._graph_query_tokens
            ):
                yield
            return
        # Uncaptured forwards retain native verification; only the prepared
        # token-capacity graph path may shorten target work.
        yield

    def idle_forward_global_num_tokens(
        self,
        global_num_tokens: list[int],
        global_bs: list[int],
        *,
        global_num_decodes: list[int],
    ) -> list[list[int]]:
        # Only decode requests draft; all ranks join if any rank has decodes.
        if not any(global_num_decodes):
            return []
        return [[batch * self.block_size for batch in global_num_decodes]]

    def wire_target(self, target_model) -> None:
        """Bind execution resources; model setup already configured capture."""
        self.target_model = target_model
        self.lm_head = self.draft_model.lm_head
        self.tp_group = target_model.logits_processor.tp_group

    def prepare_request_state(
        self,
        admission_ids: Sequence[int],
        request_pool_indices: Sequence[int],
        num_extends: int,
    ) -> None:
        """Reset predictions for new admissions; KV remains scheduler-owned."""
        if self.verify_feedback is not None:
            self._poll_verify_feedback()
            self.verify_feedback.prepare(
                admission_ids, request_pool_indices, num_extends=num_extends
            )
        if self.confidence_scores is None:
            return
        for row, (admission, slot) in enumerate(
            zip(admission_ids, request_pool_indices, strict=True)
        ):
            if row < num_extends or self._confidence_admission_ids[slot] != admission:
                self.confidence_scores[slot].fill_(float("inf"))
            self._confidence_admission_ids[slot] = admission

    def install_verify_calibration(
        self, profiles: tuple[VerifyCalibration, ...], *, policy_ms: float
    ) -> None:
        """Install rank-consistent startup measurements, never a serving-time file."""
        if self.verify_budget_policy is None:
            raise ValueError("verification budget mode is disabled")
        if not math.isfinite(policy_ms) or policy_ms < 0:
            raise ValueError("policy overhead must be finite and nonnegative")
        for index, profile in enumerate(profiles):
            if profile.verify_width != self.spec_num_tokens:
                raise ValueError("calibration verify width does not match the model")
            for capacity, _ in profile.adaptive_step_ms:
                if (profile.batch_size, capacity) not in self._verify_budget_graphs:
                    raise ValueError("calibration refers to an uncaptured allocation")
            for previous in profiles[:index]:
                if previous.batch_size == profile.batch_size and max(
                    previous.min_context, profile.min_context
                ) <= min(previous.max_context, profile.max_context):
                    raise ValueError("ambiguous calibration context coverage")
        self._verify_calibrations = tuple(profiles)
        self._verify_policy_ms = policy_ms

    @property
    def _verification_group(self) -> tuple[int, ...]:
        mapping = self.draft_model.mapping.attn
        if mapping.dp_size > 1:
            # PP1 is required: every attention rank participates in shared MoE.
            return tuple(range(mapping.world_size))
        return self.tp_group

    @property
    def _verification_rank(self) -> int:
        mapping = self.draft_model.mapping.attn
        return int(mapping.rank if mapping.dp_size > 1 else mapping.tp_rank)

    @property
    def _verification_host_group(self):
        return pg_manager.get_process_group(
            "gloo", self._verification_group, name="dsv41_verify_metadata"
        )

    def _record_verify_budget(
        self,
        *,
        batch_size: int,
        query_capacity: int,
        reason: str,
        context_bounds: tuple[int, int] | None,
    ) -> None:
        """Report host decisions without device reads or extra collectives."""
        if self._verification_rank != 0 and not self.dp_local_graph:
            return
        key = (batch_size, query_capacity, reason)
        counts = self._verify_budget_counts
        counts[key] = counts.get(key, 0) + 1
        if context_bounds is not None:
            previous = self._verify_budget_context_bounds
            self._verify_budget_context_bounds = (
                context_bounds
                if previous is None
                else (
                    min(previous[0], context_bounds[0]),
                    max(previous[1], context_bounds[1]),
                )
            )
        steps = sum(counts.values())
        if steps % 1024 == 0:
            logger.info(
                f"Adaptive DSpark budget decisions: steps={steps}, "
                f"context_bounds={self._verify_budget_context_bounds}, "
                f"counts={counts}"
            )

    def _prepare_dp_verify_budget(
        self, *, batch_size: int, actual_bs: int, rank_sizes: list[int]
    ) -> int:
        """Agree one physical capacity while keeping each DP rank's scores."""
        full = batch_size * self.spec_num_tokens
        buffers = self._verify_budget_buffers[batch_size]
        scores = self.verify_feedback.scores()
        bounds = self.verify_feedback.context_bounds()
        packet = torch.full(
            buffers.packet.shape, float("nan"), dtype=torch.float32, pin_memory=True
        )
        packet[2] = actual_bs
        if actual_bs == 0:
            packet[:2] = 0
            packet[3:] = 0
        elif scores is not None and len(scores) == actual_bs and bounds is not None:
            packet[:2] = torch.tensor(bounds, dtype=torch.float32)
            packet[3:] = 0
            packet[3 : 3 + actual_bs * self.block_size].copy_(
                torch.tensor(scores, dtype=torch.float32).flatten()
            )
        # Host feedback and scheduler counts avoid any device readback.
        torch.distributed.all_gather_into_tensor(
            buffers.peers.flatten(), packet, group=self._verification_host_group
        )
        peers = buffers.peers.tolist()
        selected = full
        reason = "feedback_unavailable"
        context_bounds = None
        ready = all(
            int(peer[2]) == count
            and all(
                math.isfinite(value) for value in peer[: 3 + count * self.block_size]
            )
            for peer, count in zip(peers, rank_sizes, strict=True)
        )
        if ready:
            active_peers = [
                peer for peer, count in zip(peers, rank_sizes, strict=True) if count
            ]
            lower = min(int(peer[0]) for peer in active_peers)
            upper = max(int(peer[1]) for peer in active_peers)
            context_bounds = (lower, upper)
            reason = "uncalibrated"
            tp = int(self.draft_model.mapping.attn.tp_size)
            rank_scores = [
                [
                    peer[3 + i * self.block_size : 3 + (i + 1) * self.block_size]
                    for i in range(count)
                ]
                for peer, count in zip(peers[::tp], rank_sizes[::tp], strict=True)
            ]
            # Endpoint timings represent the global upper-context bucket.
            # Shorter peers may occupy different buckets in the same step.
            for profile in self._verify_calibrations:
                if profile.covers(
                    batch_size=batch_size, min_context=upper, max_context=upper
                ):
                    selected = self.verify_budget_policy.select_distributed(
                        rank_scores,
                        graph_batch_size=batch_size,
                        native_step_ms=profile.native_step_ms,
                        adaptive_step_ms=dict(profile.adaptive_step_ms),
                        policy_ms=self._verify_policy_ms,
                    )
                    reason = "packed" if selected != full else "full"
                    break
        if selected != full:
            buffers.packet.copy_(packet, non_blocking=True)
            history = buffers.packet[3:].view(batch_size, self.block_size)
            self.prepare_verify_budget_layout(
                history, batch_size=batch_size, query_capacity=selected
            )
        self._record_verify_budget(
            batch_size=batch_size,
            query_capacity=selected,
            reason=reason,
            context_bounds=context_bounds,
        )
        return selected

    def _prepare_calibrated_budget(self, *, actual_bs: int, padded_bs: int) -> int:
        full = padded_bs * self.spec_num_tokens
        admitted = (
            actual_bs >= self.adaptive_min_batch_size
            if self.dp_local_graph
            else self.verify_budget_policy.admits(
                batch_size=actual_bs, graph_batch_size=padded_bs
            )
        )
        if not admitted or padded_bs not in self._verify_budget_buffers:
            return full
        self._poll_verify_feedback()
        buffers = self._verify_budget_buffers[padded_bs]
        tp = int(self.draft_model.mapping.attn.tp_size)
        rank = int(self.draft_model.mapping.attn.tp_rank)
        selected = full
        scores = None
        bounds = None
        reason = "feedback_unavailable"
        if rank == 0:
            scores = self.verify_feedback.scores()
            bounds = self.verify_feedback.context_bounds()
            if scores is not None and bounds is not None:
                reason = "uncalibrated"
                # Use the same upper-context bucket as attention DP.
                for profile in self._verify_calibrations:
                    if profile.covers(
                        batch_size=padded_bs,
                        min_context=bounds[1],
                        max_context=bounds[1],
                    ):
                        selected = self.verify_budget_policy.select_distributed(
                            (scores,),
                            graph_batch_size=padded_bs,
                            native_step_ms=profile.native_step_ms,
                            adaptive_step_ms=dict(profile.adaptive_step_ms),
                            policy_ms=self._verify_policy_ms,
                        )
                        reason = "packed" if selected != full else "full"
                        break
        # One authoritative packet aligns graph choice and allocation scores.
        # All TP ranks participate even when their local async feedback is late.
        packet = torch.zeros(buffers.packet.shape, dtype=torch.float32, pin_memory=True)
        packet[0] = selected
        packet[2] = actual_bs
        if rank == 0 and selected != full:
            packet[3 : 3 + actual_bs * self.block_size].copy_(
                torch.tensor(scores, dtype=torch.float32).flatten()
            )
        if tp > 1:
            torch.distributed.broadcast(
                packet,
                src=self.tp_group[0],
                group=pg_manager.get_process_group(
                    "gloo", self.tp_group, name="dsv41_verify_tp_metadata"
                ),
            )
            selected = int(packet[0].item())
        if selected != full:
            buffers.packet.copy_(packet, non_blocking=True)
            source = buffers.packet[3:].view(padded_bs, self.block_size)
            self.prepare_verify_budget_layout(
                source, batch_size=padded_bs, query_capacity=selected
            )
        self._record_verify_budget(
            batch_size=padded_bs,
            query_capacity=selected,
            reason=reason,
            context_bounds=bounds,
        )
        return selected

    def capture_round_graphs(
        self, graph_bs: int, *, stream: torch.cuda.Stream, pool: tuple[int, int]
    ) -> None:
        if self.verify_budget_policy is None or graph_bs < self.adaptive_min_batch_size:
            return
        if graph_bs * self.spec_num_tokens > dsv41.VERIFY_LAYOUT_MAX_TOKENS:
            logger.info(
                f"Adaptive DSpark retains native verification for capture bucket: "
                f"batch_size={graph_bs}, verify_width={self.spec_num_tokens}, "
                f"layout_limit={dsv41.VERIFY_LAYOUT_MAX_TOKENS}"
            )
            return
        if graph_bs in self._verify_budget_buffers:
            return
        if len(self._verification_group) > 1:
            pg_manager.init_process_group(
                self._verification_group,
                backend="gloo",
                name="dsv41_verify_metadata",
            )
        if len(self.tp_group) > 1:
            pg_manager.init_process_group(
                self.tp_group, backend="gloo", name="dsv41_verify_tp_metadata"
            )
        buffers = _VerifyBudgetBuffers(
            scores=torch.zeros(
                (graph_bs, self.block_size), dtype=torch.float32, device=self.device
            ),
            counts=torch.empty(graph_bs, dtype=torch.int64, device=self.device),
            valid=torch.empty((), dtype=torch.bool, device=self.device),
            packet=torch.empty(
                3 + graph_bs * self.block_size, dtype=torch.float32, device=self.device
            ),
            peers=torch.empty(
                (
                    len(self._verification_group),
                    3 + graph_bs * self.block_size,
                ),
                dtype=torch.float32,
                device="cpu",
            ),
        )
        buffers.packet[2].fill_(graph_bs)
        self._verify_budget_buffers[graph_bs] = buffers
        for capacity in self.decode_graph_query_capacities(graph_bs):
            if capacity == graph_bs * self.spec_num_tokens:
                continue

            def allocate() -> None:
                dsv41.verify_layout(
                    buffers.scores,
                    query_capacity=capacity,
                    rows_out=self._verify_rows[:capacity],
                    indptr_out=self._verify_indptr[: graph_bs + 1],
                    counts_out=buffers.counts,
                    valid_out=buffers.valid,
                    active_count=(
                        buffers.packet[2:3]
                        if self.dp_local_graph
                        or self.draft_model.mapping.attn.dp_size > 1
                        else None
                    ),
                    latest_scores=(
                        self.confidence_scores
                        if self.dp_local_graph
                        or self.draft_model.mapping.attn.dp_size > 1
                        else None
                    ),
                    request_slots=(
                        self.input_buffers.req_pool_indices_buf[:graph_bs]
                        if self.dp_local_graph
                        or self.draft_model.mapping.attn.dp_size > 1
                        else None
                    ),
                )

            stream.wait_stream(torch.cuda.current_stream())
            with torch.cuda.stream(stream):
                for _ in range(3):
                    allocate()
            torch.cuda.current_stream().wait_stream(stream)
            graph = torch.cuda.CUDAGraph()
            with torch.cuda.graph(graph, pool=pool, stream=stream):
                allocate()
            self._verify_budget_graphs[(graph_bs, capacity)] = graph
        self._verify_layout_counts = None
        self._restore_verify_calibration(graph_bs)

