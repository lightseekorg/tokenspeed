    def _restore_verify_calibration(self, graph_bs: int) -> None:
        self._initialize_verify_cache()
        candidates = tuple(
            profile
            for profile in self._cached_verify_profiles
            if profile.batch_size == graph_bs
            and profile.verify_width == self.spec_num_tokens
            and profile.sample_count >= 8
            and {q for q, _ in profile.adaptive_step_ms}
            == set(self.decode_graph_query_capacities(graph_bs))
            - {graph_bs * self.spec_num_tokens}
        )
        if candidates:
            self.install_verify_calibration(
                (*self._verify_calibrations, *candidates), policy_ms=0.0
            )
            logger.info(
                f"Adaptive DSpark loaded {len(candidates)} calibration regions for BS={graph_bs}"
            )

    def _save_verify_calibration(self) -> None:
        self._cached_verify_profiles = self._verify_calibrations
        if self._verify_cache is not None:
            try:
                # Happens only on profile completion, before the timed forward.
                self._verify_cache.save(self._verify_calibrations)
            except OSError as error:
                logger.warning(
                    f"Adaptive DSpark could not persist calibration: {error}"
                )
                self._verify_cache = None

    def release_round_graphs(self) -> None:
        # Pending D2H copies retain their buffers until completion. Invalidate
        # their request epochs so they cannot seed a rebuilt execution graph.
        if self.verify_feedback is not None:
            self.verify_feedback.invalidate()
        self._verify_calibrations = ()
        self._verify_policy_ms = None
        self._verify_budget_graphs.clear()
        self._verify_budget_buffers.clear()

    def prepare_verify_budget_layout(
        self, scores: torch.Tensor, *, batch_size: int, query_capacity: int
    ) -> None:
        """Replay a startup-prepared allocation; never capture on the serving path.

        The budget owner must have validated the feedback and agreed on capacity
        across ranks. The validity flag remains available for diagnostics.
        """
        graph = self._verify_budget_graphs.get((batch_size, query_capacity))
        if graph is None:
            raise ValueError("verification allocation graph was not prepared")
        buffers = self._verify_budget_buffers[batch_size]
        if (
            scores.shape != buffers.scores.shape
            or scores.dtype != torch.float32
            or scores.device != buffers.scores.device
        ):
            raise ValueError("confidence scores do not match the prepared allocation")
        buffers.scores.copy_(scores)
        graph.replay()
        self._verify_layout_counts = None

    def _poll_verify_feedback(self) -> None:
        if self.verify_feedback is None:
            return
        while self._pending_verify_feedback:
            pending = self._pending_verify_feedback[0]
            if not pending.ready.query():
                break
            self._pending_verify_feedback.pop(0)
            lengths = pending.contexts.tolist()
            if lengths and all(length > 0 for length in lengths):
                self.verify_feedback.publish(
                    pending.snapshot, pending.scores.tolist(), context_lengths=lengths
                )

    def finish_round(self, ctx: ForwardContext, graph_bs: int | None) -> None:
        # Runs on the forward thread, outside capture, after draft writes.
        # Do not wait for feedback; a busy copy queue means native fallback.
        if (
            self.verify_feedback is None
            or ctx.num_extends
            or graph_bs is None
            or graph_bs < ctx.bs
            or ctx.bs == 0
            or (ctx.bs if self.dp_local_graph else max(ctx.global_bs or (ctx.bs,)))
            < self.adaptive_min_batch_size
            or (
                self.draft_model.mapping.attn.dp_size == 1
                and not self.dp_local_graph
                and (graph_bs != ctx.bs or ctx.bs < self.adaptive_min_batch_size)
            )
        ):
            return
        self._poll_verify_feedback()
        if len(self._pending_verify_feedback) >= 3:
            return
        snapshot = self.verify_feedback.snapshot()
        if len(snapshot) != ctx.bs:
            raise RuntimeError("verification feedback does not match the active batch")
        slots = self.input_buffers.req_pool_indices_buf[: ctx.bs]
        scores = self.confidence_scores.index_select(0, slots)
        host = torch.empty(
            scores.shape, dtype=scores.dtype, device="cpu", pin_memory=True
        )
        host.copy_(scores, non_blocking=True)
        contexts = torch.empty(
            ctx.bs,
            dtype=self.input_buffers.seq_lens_buf.dtype,
            device="cpu",
            pin_memory=True,
        )
        contexts.copy_(self.input_buffers.seq_lens_buf[: ctx.bs], non_blocking=True)
        event = torch.cuda.Event()
        event.record()
        self._pending_verify_feedback.append(
            _PendingVerifyFeedback(event, host, contexts, snapshot)
        )

    def _draft_decode_rows(
        self,
        base_ctx: ForwardContext,
        start_pos: torch.Tensor,
        next_tokens: torch.Tensor,
    ) -> None:
        num_extends = base_ctx.num_extends
        num_decodes = base_ctx.bs - num_extends
        global_num_decodes = base_ctx.global_num_decodes
        if global_num_decodes is None and base_ctx.global_bs is not None:
            raise RuntimeError("DSpark attention DP requires per-rank decode counts")
        if num_decodes == 0 and not any(global_num_decodes or []):
            return
        backend = base_ctx.attn_backend
        pool = base_ctx.token_to_kv_pool
        draft_ctx = ForwardContext(
            attn_backend=backend,
            token_to_kv_pool=pool,
            bs=num_decodes,
            num_extends=0,
            output_layout=ForwardOutputLayout(0, 0, num_decodes, self.block_size),
            input_num_tokens=num_decodes * self.block_size,
            forward_mode=ForwardMode.DECODE,
            capture_hidden_mode=CaptureHiddenMode.NULL,
            global_num_tokens=(
                [batch * self.block_size for batch in global_num_decodes]
                if global_num_decodes is not None and not self.dp_local_graph
                else None
            ),
            # global_bs keeps the round's total request counts, as in the idle
            # ranks' draft context; the decode-only counts the draft sizes by
            # ride in global_num_decodes and global_num_tokens.
            global_bs=base_ctx.global_bs,
            global_num_decodes=global_num_decodes,
            all_decode_or_idle=base_ctx.all_decode_or_idle,
        )
        if num_decodes == 0:
            # A prefill-only rank still joins the peers' draft MoE collectives.
            draft_ctx.forward_mode = ForwardMode.IDLE
            empty = next_tokens.new_empty(0)
            self.draft_model_runner.forward(draft_ctx, input_ids=empty, positions=empty)
            return
        meta = backend.query_metadata(ForwardMode.DECODE)
        width = self.spec_num_tokens
        # The anchor is the last accepted verify row; it and every earlier
        # accepted position were written above, so history ends at start_pos.
        history_slots, _ = backend.window_slots(
            V41_SWA_GROUP_ID,
            start_pos,
            (
                meta.request_indices[: num_decodes * width : width]
                if base_ctx.decode_query_indptr is None
                else meta.request_indices.index_select(
                    0, base_ctx.decode_query_indptr[:-1].to(torch.int64)
                )
            ),
        )
        bonus = next_tokens[num_extends:, 0]
        capture = (
            None
            if self.confidence_features is None
            or num_decodes < self.adaptive_min_batch_size
            else self.confidence_features[:num_decodes]
        )
        draft_hidden = self.model.forward_backbone(
            bonus,
            start_pos,
            history_slots,
            pool,
            draft_ctx,
            confidence_hidden_out=capture,
        )
        local_logits = self.model.local_base_logits(draft_hidden, self.lm_head.weight)
        # The greedy step's shard offsets come from the Markov projection, so
        # the target head's logits must span its local vocabulary.
        markov_vocab = int(self.model.markov_projection.num_embeddings_per_partition)
        if local_logits.shape[-1] != markov_vocab:
            raise ValueError(
                "DSpark base logits do not span the Markov projection's local "
                f"vocabulary: {local_logits.shape[-1]} != {markov_vocab}"
            )
        if self._sample_proposals is None:
            sample_dspark_block_greedy(
                local_logits,
                bonus,
                self.model.markov_head,
                # The target head is ReplicatedLinear under DP; the Markov head
                # retains the identical vocabulary layout, including TP padding.
                self.model.markov_projection,
                self.tp_group,
                self.candidates,
                self.partials,
                next_tokens[num_extends:, 1:],
            )
        else:
            from tokenspeed_kernel.ops.sampling.packed_verify import DRAFT_POS_HASH_MUL

            slots = self.input_buffers.req_pool_indices_buf[num_extends : base_ctx.bs]
            write_slots = self.input_buffers.state_write_req_pool_indices_buf[
                num_extends : base_ctx.bs
            ]
            previous = bonus.clamp(0, self.vocab_size - 1)
            for step in range(self.block_size):
                markov = self.model.markov_embedding(previous)
                bias = torch.mm(
                    markov,
                    self.model.markov_projection.weight.T,
                    out_dtype=torch.float32,
                )
                logits = (local_logits[:, step] + bias)[
                    :, : self.vocab_size
                ].contiguous()
                sampled = torch.empty(
                    num_decodes, dtype=torch.int32, device=self.device
                )
                probabilities = self._sample_proposals(
                    logits,
                    slots,
                    start_pos.to(torch.int64) + 1 + (step + 1) * DRAFT_POS_HASH_MUL,
                    sampled,
                )
                self.runtime_states.draft_probs[:, step].index_copy_(
                    0, write_slots, probabilities
                )
                next_tokens[num_extends:, step + 1].copy_(sampled)
                previous = sampled
        if capture is not None:
            scores = self.model.confidence_logits(
                capture, next_tokens[num_extends:, :-1]
            )
            slots = self.input_buffers.state_write_req_pool_indices_buf[
                num_extends : base_ctx.bs
            ]
            self.confidence_scores.index_copy_(0, slots, scores)

    @nvtx_range("drafter:dspark", color="purple")
    def run(
        self,
        base_ctx: ForwardContext,
        logits_output: LogitsProcessorOutput,
        output_tokens: torch.Tensor,
        accept_lengths: torch.Tensor,
    ) -> torch.Tensor:
        if self.target_model is None:
            raise RuntimeError("DSPARK drafter is not bound to the target model.")
        hidden_states = logits_output.hidden_states
        if hidden_states is None:
            raise RuntimeError("DSPARK requires target hidden-state captures.")
        if hidden_states.ndim != 2 or hidden_states.shape[1] != self.hidden_width:
            raise RuntimeError(
                "DSPARK target hidden-state shape mismatch: "
                f"expected [tokens, {self.hidden_width}], got "
                f"{tuple(hidden_states.shape)}."
            )
        backend = base_ctx.attn_backend
        pool = base_ctx.token_to_kv_pool
        num_extends = base_ctx.num_extends
        # The taps were captured on the decoder view: each extend request's
        # kept tail, then the decode rows (graph padding rows after them).
        view = backend.decoder_view()
        prefill_tokens = 0 if view.prefill is None else view.prefill.positions.numel()
        num_decodes = base_ctx.bs - num_extends
        decode_tokens = (
            num_decodes * self.spec_num_tokens
            if base_ctx.decode_query_indptr is None
            else view.metadata.positions.numel() - prefill_tokens
        )
        rows = prefill_tokens + decode_tokens
        if rows > hidden_states.shape[0] or rows > view.metadata.positions.numel():
            raise RuntimeError(
                "DSPARK token rows exceed captured hidden-state rows: "
                f"{rows} > {hidden_states.shape[0]}."
            )

        # Output-bearing rows get their bonus token as next-round row
        # (completing prefills keep it; decode rows overwrite the proposal
        # columns below), and each decode request's anchor is its last
        # accepted verify position. Incomplete prefills have no token, so
        # their rows in [num_prefill_outputs, num_extends) are left as is.
        next_tokens = self.next_tokens_buf[: base_ctx.bs]
        start_pos = self.start_pos_buf[:num_decodes]
        if rows == 0:
            self._draft_decode_rows(base_ctx, start_pos, next_tokens)
            return next_tokens

        num_prefill_outputs = base_ctx.output_layout.num_prefill_outputs
        dsv41.dspark_anchors(
            output_tokens,
            accept_lengths,
            view.metadata.positions[prefill_tokens:rows],
            num_extends,
            self.spec_num_tokens,
            next_tokens,
            start_pos,
            num_prefill_outputs=num_prefill_outputs,
            decode_query_indptr=base_ctx.decode_query_indptr,
        )

        # Every captured row writes its window row: a prompt's kept tail seeds
        # the history the first decode reads, verify rows refresh the block
        # just verified. Rejected rows sit past the anchor and are rewritten
        # by the step that accepts them.
        self.model.write_context_kv(
            hidden_states[:rows],
            view.metadata.positions[:rows],
            view.metadata.swa_write_slots[:rows],
            pool,
        )
        self._draft_decode_rows(base_ctx, start_pos, next_tokens)
        next_tokens[:num_prefill_outputs].clamp_(0, int(self.vocab_size) - 1)
        next_tokens[num_extends:].clamp_(0, int(self.vocab_size) - 1)
        return next_tokens

    def draft(self, *args, **kwargs) -> torch.Tensor | None:
        raise RuntimeError("DSPARK drafts through run() with target captures.")

    @torch.inference_mode()
    def profile_startup(self, executor: ModelExecutor) -> None:
        """Profile final DSpark decode graphs before admitting live requests.

        This DSpark companion uses the runner's capture metadata/replay/reset
        lifecycle. Post-graph feedback collection is outside the measured interval.
        """
        import numpy as np

        from tokenspeed.runtime.execution.drafter.verify_calibration import (
            STARTUP_CONTEXT_ENDPOINTS,
            STARTUP_MEASURED_REPLAYS,
            STARTUP_WARMUP_REPLAYS,
            VerifyCalibration,
        )
        from tokenspeed.runtime.execution.drafter.verify_feedback import VerifyFeedback
        from tokenspeed.runtime.execution.drafter.verify_startup import (
            agree_startup_profile,
            measure_startup_graph,
            plan_profile_cache,
            preserve_profile_tensors,
            profile_decode_context,
        )
        from tokenspeed.runtime.sampling.backends.base import CUDA_GRAPH_VARIANT_DEFAULT

        runner = executor.forward_step
        drafter = self
        if runner.disable:
            return
        if not drafter._verify_budget_buffers:
            return
        arena = runner.token_to_kv_pool.arena
        device = torch.device(runner.device)
        group = (
            drafter._verification_host_group
            if len(drafter._verification_group) > 1
            else None
        )
        width = drafter.spec_num_tokens
        maximum = int(executor.config.context_len)
        endpoints = sorted(
            {min(n, maximum) for n in (*STARTUP_CONTEXT_ENDPOINTS, maximum)}
        )
        ib = runner.input_buffers
        old_feedback = drafter.verify_feedback
        installed = drafter._verify_calibrations
        old_policy_ms = drafter._verify_policy_ms
        try:
            for bs in sorted(drafter._verify_budget_buffers):
                capacities = drafter.decode_graph_query_capacities(bs)
                lower = 1
                for context in endpoints:
                    if context < width:
                        continue
                    if any(
                        p.covers(batch_size=bs, min_context=lower, max_context=context)
                        for p in installed
                    ):
                        lower = context + 1
                        continue
                    # A full step drafts beyond the last accepted target position.
                    # At the model limit, measure just below the endpoint rather than
                    # indexing outside RoPE; the calibration interval stays unchanged.
                    measured_context = profile_decode_context(
                        context,
                        max_positions=min(
                            maximum, int(drafter.model.config.max_position_embeddings)
                        ),
                        verify_width=width,
                        draft_width=drafter.block_size,
                    )
                    plan = plan_profile_cache(
                        arena.cache_group_specs,
                        virtual_packing=arena.runtime_contract.virtual_packing,
                        page_counts=arena.cache_group_page_counts,
                        batch_size=bs,
                        context_length=measured_context,
                        verify_width=width,
                        overlap_schedule_depth=runner.overlap_schedule_depth,
                    )
                    graphs = {
                        q: runner.decode_graph_for_profile(
                            bs=bs, query_tokens=q, variant=CUDA_GRAPH_VARIANT_DEFAULT
                        )
                        for q in capacities
                    }
                    available = plan is not None and all(
                        graph is not None for graph in graphs.values()
                    )
                    if not agree_startup_profile(
                        available=available,
                        batch_size=bs,
                        context_length=context,
                        capacities=capacities,
                        host_group=group,
                    ):
                        if drafter._verification_rank == 0:
                            logger.warning(
                                f"Adaptive DSpark startup profile unavailable: "
                                f"local_bs={bs}, context=[{lower}, {context}]; "
                                "using full verification"
                            )
                        lower = context + 1
                        continue
                    assert plan is not None
                    tables = {
                        g.group_id: torch.tensor(
                            g.block_tables(), dtype=torch.int32, device=device
                        )
                        for g in plan
                    }
                    blocks = {
                        g.group_id: np.arange(g.first_page, g.page_stop, dtype=np.int32)
                        for g in plan
                    }
                    tensors = [
                        ib.input_ids_buf[: bs * width],
                        ib.positions_buf[: bs * width],
                        ib.req_pool_indices_buf[:bs],
                        ib.state_write_req_pool_indices_buf[:bs],
                        ib.seq_lens_buf[:bs],
                    ]
                    for owner in executor.slot_state_exporters():
                        for slot in range(bs):
                            tensors.extend(owner.slot_state_rows(slot))
                    measured = {}
                    try:
                        with (
                            runner.decode_profile_metadata(
                                bs=bs,
                                variant=CUDA_GRAPH_VARIANT_DEFAULT,
                                block_tables=tables,
                            ) as prepare_metadata,
                            preserve_profile_tensors(tensors),
                        ):
                            arena.zero_blocks(blocks)
                            slots = torch.arange(
                                bs, device=device, dtype=ib.req_pool_indices_buf.dtype
                            )
                            ib.req_pool_indices_buf[:bs].copy_(slots)
                            ib.state_write_req_pool_indices_buf[:bs].copy_(slots)
                            ids = [f"startup-profile-{i}" for i in range(bs)]
                            feedback = VerifyFeedback(draft_width=width - 1)
                            for _ in range(3):
                                feedback.prepare(ids, list(range(bs)), num_extends=0)
                                feedback.publish(
                                    feedback.snapshot(),
                                    [[0.0] * (width - 1)] * bs,
                                    context_lengths=[
                                        max(1, measured_context - 2 * width)
                                    ]
                                    * bs,
                                )
                            drafter.verify_feedback = feedback
                            for q in reversed(capacities):
                                # Force exactly this prepared tier through the normal
                                # host policy path; no acceptance result is overridden.
                                drafter._verify_calibrations = (
                                    VerifyCalibration(
                                        bs,
                                        1,
                                        maximum + 2 * width,
                                        width,
                                        1e9,
                                        tuple(
                                            (capacity, 1.0 if capacity == q else 1e9)
                                            for capacity in capacities
                                            if capacity < bs * width
                                        ),
                                        8,
                                    ),
                                )
                                drafter._verify_policy_ms = 0.0

                                def prepare():
                                    ib.input_ids_buf[: bs * width].copy_(
                                        (
                                            torch.arange(bs * width, device=device)
                                            + 17
                                            + runner.global_rank * 101
                                        )
                                        % runner.vocab_size
                                    )
                                    ib.positions_buf[: bs * width].copy_(
                                        torch.arange(
                                            measured_context - width,
                                            measured_context,
                                            device=device,
                                        ).repeat(bs)
                                    )
                                    ib.seq_lens_buf[:bs].fill_(measured_context)
                                    states = executor.runtime_states
                                    states.valid_cache_lengths[:bs].fill_(
                                        measured_context - width
                                    )
                                    states.spec_candidates_ready[:bs].fill_(True)
                                    states.stopped[:bs].zero_()
                                    states.stop_token_ids[:bs].fill_(-1)
                                    states.token_limits[:bs].fill_(
                                        torch.iinfo(torch.int32).max
                                    )
                                    prepare_metadata()

                                rank_sizes = [bs] * len(drafter._verification_group)

                                def replay(*, rank_sizes=rank_sizes):
                                    if q < bs * width:
                                        # Every rank profiles the same balanced
                                        # workload through the serving agreement.
                                        chosen = drafter._prepare_verify_budget(
                                            actual_bs=bs,
                                            padded_bs=bs,
                                            rank_sizes=rank_sizes,
                                        )
                                        if chosen != q:
                                            raise RuntimeError(
                                                "startup profiling selected "
                                                "a different graph"
                                            )
                                    graph = graphs[q]
                                    assert graph is not None
                                    graph.replay()

                                executor.nan_guard.reset(bs)
                                measured[q] = measure_startup_graph(
                                    replay,
                                    prepare,
                                    device=device,
                                    host_group=group,
                                    warmup=STARTUP_WARMUP_REPLAYS,
                                    samples=STARTUP_MEASURED_REPLAYS,
                                )
                                flags = executor.nan_guard.flags_cpu
                                torch.cuda.synchronize(device)
                                valid = flags is None or not bool(flags.any())
                                if not agree_startup_profile(
                                    available=valid,
                                    batch_size=bs,
                                    context_length=context,
                                    capacities=(q,),
                                    host_group=group,
                                ):
                                    raise RuntimeError(
                                        "non-finite synthetic startup profile"
                                    )
                            torch.cuda.synchronize(device)
                    finally:
                        torch.cuda.synchronize(device)
                        arena.zero_blocks(blocks)
                        executor.nan_guard.reset(0)
                        drafter._verify_calibrations = installed
                        drafter._verify_policy_ms = old_policy_ms
                    profile = VerifyCalibration.measure(
                        batch_size=bs,
                        min_context=lower,
                        max_context=context,
                        verify_width=width,
                        native_samples=measured[bs * width],
                        adaptive_samples={
                            q: values
                            for q, values in measured.items()
                            if q != bs * width
                        },
                        minimum_samples=STARTUP_MEASURED_REPLAYS,
                    )
                    installed = (*installed, profile)
                    # Shortened replay costs already include policy and agreement.
                    drafter.install_verify_calibration(installed, policy_ms=0.0)
                    drafter._save_verify_calibration()
                    if drafter._verification_rank == 0:
                        logger.info(
                            f"Adaptive DSpark startup profile complete: local_bs={bs}, "
                            f"context=[{lower}, {context}], "
                            f"measured_context={measured_context}, "
                            f"full_ms={profile.native_step_ms:.3f}, "
                            f"adaptive_ms={dict(profile.adaptive_step_ms)}"
                        )
                    lower = context + 1
        finally:
            torch.cuda.synchronize(device)
            drafter.verify_feedback = old_feedback
            drafter._verify_calibrations = installed
            drafter._verify_policy_ms = 0.0 if installed else old_policy_ms
            drafter._verify_budget_counts.clear()
            drafter._verify_budget_context_bounds = None
