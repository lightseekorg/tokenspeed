from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field, replace
from typing import Literal, get_args

from tokenspeed.runtime.layers.attention.kv_cache.recipes import plan

# The one classification of a cache group -- the C++ scheduler's AttnKind.
# ``full_history`` and ``sliding_window`` groups hold rows of token history
# (the latter keeps only its trailing window resident); a ``state`` group holds
# whole recurrent states and spans no tokens.
AttnKind = Literal["full_history", "sliding_window", "state"]
ATTN_KINDS: frozenset[str] = frozenset(get_args(AttnKind))
TransferPolicy = Literal["full_suffix", "latest_snapshot"]
# How a caller spells sliding windows: one window broadcast to every sliding
# layer (today's HF scalar), one entry per layer (multi-window models, with
# None at full-history positions), or None for a model with no sliding layers.
SlidingWindowTokens = int | Sequence[int | None] | None

# A state group's block table holds two slots per request: the input
# checkpoint the forward reads (a claimed prefix hit, the block the previous
# forward wrote before the scheduler rotated it, or a fresh zeroed block for a
# prompt with no history; null once consumed) and the live block it writes.
# The scheduler and the state kernels address them by these fixed positions.
STATE_INPUT_SLOT = 0
STATE_LIVE_SLOT = 1
STATE_TABLE_SLOTS = 2
# A prefill that writes an in-forward State checkpoint carries a third entry:
# the block that receives the state at the checkpoint inside its chunk.
STATE_CHECKPOINT_SLOT = 2


@dataclass(frozen=True)
class CacheGroupSpec:
    """One cache group's scheduler-facing layout.

    The kind names the geometry a spec declares:

    * **Row geometry** (``rows_per_page`` + ``entry_stride_tokens``) -- the
      ``"full_history"`` and ``"sliding_window"`` kinds: paged KV-cache
      consumers whose CacheBlocks physically hold rows of entries (per-token
      KV, sliding windows, compressed entries). A sliding group keeps only its
      trailing ``sliding_window_tokens`` resident.
    * **No span** -- the ``"state"`` kind: snapshot-style groups
      (recurrent/conv state) whose CacheBlocks each hold one state. A state
      summarizes everything before it, so a block covers no token span and
      nothing in it ever slides out. The scheduler keeps two blocks per live
      request (the input checkpoint it resumes from and the live block it
      writes) and publishes a block under the token count at which the
      forward that wrote it ended.

    Kind-agnostic consumers address row geometry through
    ``block_granularity``; a state group has none.
    """

    group_id: str
    attn_kind: AttnKind
    rows_per_page: int | None = None
    entry_stride_tokens: int | None = None
    sliding_window_tokens: int | None = None
    # A sliding-window group regenerated by bounded replay instead of being
    # prefix-cached: the scheduler never matches, publishes or streams it and
    # re-feeds its whole sliding_window_tokens before every prefix hit so the
    # model can rebuild every row the group retains. Stated by every caller:
    # a group silently left cached would change what a prefix hit means.
    replayable: bool = field(kw_only=True)
    # None preserves standalone/non-PD behavior; PD plans set this explicitly.
    transfer_policy: TransferPolicy | None = None

    # Number of cyclic owners of this group's virtual blocks. One keeps the
    # same block IDs on every rank; local field geometry is independent of it.
    shard_count: int = 1

    def __post_init__(self) -> None:
        if (
            isinstance(self.shard_count, bool)
            or not isinstance(self.shard_count, int)
            or self.shard_count <= 0
        ):
            raise ValueError("shard_count must be a positive integer")
        if self.attn_kind not in ATTN_KINDS:
            raise ValueError(
                f"group {self.group_id!r}: unknown cache-group kind {self.attn_kind!r}; "
                f"expected one of {sorted(ATTN_KINDS)}"
            )
        if self.attn_kind == "sliding_window":
            if self.sliding_window_tokens is None or self.sliding_window_tokens <= 0:
                raise ValueError(
                    f"group {self.group_id!r}: a sliding-window group needs a "
                    f"positive sliding_window_tokens, got {self.sliding_window_tokens!r}"
                )
        elif self.sliding_window_tokens is not None:
            raise ValueError(
                f"group {self.group_id!r}: only a sliding-window group carries "
                f"sliding_window_tokens; a {self.attn_kind} group keeps every row"
            )
        if self.replayable and self.attn_kind != "sliding_window":
            raise ValueError(
                f"group {self.group_id!r}: only a sliding-window group can "
                "be regenerated by bounded replay; a full-history group is "
                "prefix-closed and shared, a state group is a checkpoint"
            )
        has_rows = (
            self.rows_per_page is not None or self.entry_stride_tokens is not None
        )
        if self.attn_kind == "state":
            if has_rows:
                raise ValueError(
                    f"group {self.group_id!r}: a state group holds one state "
                    "per block and declares no row geometry; rows of token "
                    "history -- a sliding window included -- are a "
                    "full_history or sliding_window group"
                )
            return
        if self.rows_per_page is None or self.entry_stride_tokens is None:
            raise ValueError(
                f"group {self.group_id!r}: a {self.attn_kind} group declares row "
                "geometry (rows_per_page + entry_stride_tokens)"
            )
        if self.rows_per_page <= 0 or self.entry_stride_tokens <= 0:
            raise ValueError(
                f"group {self.group_id!r}: rows_per_page and "
                "entry_stride_tokens must be > 0, got "
                f"{self.rows_per_page} and {self.entry_stride_tokens}"
            )

    @property
    def page_size(self) -> int:
        """Raw-token span of one CacheBlock; row-geometry (paged KV) only."""
        if self.rows_per_page is None or self.entry_stride_tokens is None:
            raise TypeError(
                f"group {self.group_id!r}: page_size is undefined for a "
                "state group; its blocks cover no token span"
            )
        return self.rows_per_page * self.entry_stride_tokens

    @property
    def block_granularity(self) -> int:
        """Raw-token span of one block-table slot; row geometry only."""
        return self.page_size


# One declared cache group: what the scheduler is told, and the bytes it costs.
CacheGroupDeclaration = tuple[CacheGroupSpec, tuple[plan.CacheFieldSpec, ...]]

# The scale-tile span lives with the field geometry it defines (plan.py); it is
# re-exported here because scheduler-side callers reason about the tile as a
# token span, not as a shape.
MXFP8_KV_SCALE_TILE_TOKENS = plan.MXFP8_KV_SCALE_TILE_TOKENS


def _ceil_div(dividend: int, divisor: int) -> int:
    return (dividend + divisor - 1) // divisor


# Cache-group label vocabulary (NOT the HF checkpoint's serialized enum:
# Qwen3.5 checkpoints spell full attention "attention").
FULL_ATTENTION = "full_attention"
LINEAR_ATTENTION = "linear_attention"

# layer_type label -> cache-group kind. GPT-OSS uses the first two, Qwen3.5
# GDN layers use "linear_attention"; unknown labels raise.
_LAYER_TYPE_ATTN_KIND: dict[str, AttnKind] = {
    FULL_ATTENTION: "full_history",
    "sliding_attention": "sliding_window",
    LINEAR_ATTENTION: "state",
    # DSA attends sparsely but retains the full KV history (the indexer
    # selects from it), so its layers publish as full-history groups.
    "deepseek_sparse_attention": "full_history",
}

# Labels whose group holds recurrent-state checkpoints, not rows of KV history.
STATE_LAYER_TYPES = frozenset(
    label for label, attn_kind in _LAYER_TYPE_ATTN_KIND.items() if attn_kind == "state"
)


def validate_scheduler_config(
    *,
    attn_backend: object,
    kv_pool: object,
) -> None:
    """Validate that the attention backend consumes every cache-group kind
    the KV pool's runtime contract publishes.

    Args:
        attn_backend: The (possibly composite) attention backend; composite
            backends aggregate their sub-backends' consumer kinds in their
            own ``cache_consumer_attn_kinds``.
        kv_pool: The KV pool whose ``runtime_contract`` group specs name the
            required kinds.

    Raises:
        RuntimeError: When a contract kind (e.g. a hybrid pool's ``state``
            group) has no consumer in the backend — that group's tables would
            go unread, dying on a capture-path assert at best and silently
            reading the wrong pages at worst.
    """
    contract = kv_pool.arena.runtime_contract
    required_kinds = frozenset(spec.attn_kind for spec in contract.group_specs)
    supported_kinds = frozenset(attn_backend.cache_consumer_attn_kinds)
    missing_kinds = required_kinds - supported_kinds
    if missing_kinds:
        raise RuntimeError(
            "cache pool requires consumers for cache-group kinds "
            f"{sorted(required_kinds)}, but backend "
            f"{type(attn_backend).__name__} is missing "
            f"{sorted(missing_kinds)}"
        )


def validate_state_checkpoint_in_forward(
    *,
    attn_backend: object,
    kv_pool: object,
) -> None:
    """Refuse the flag when a State group's consumer cannot store the checkpoint.

    The flag is ``--enable-state-checkpoint-in-forward``. The scheduler plans an in-forward checkpoint for every State group of a
    long prompt and publishes the third block of its rows; a consumer that
    never writes that block would publish a zeroed state as a checkpoint.

    Args:
        attn_backend: The (possibly composite) attention backend.
        kv_pool: The KV pool whose ``runtime_contract`` names the groups.

    Raises:
        ValueError: When the contract has a State group and the backend does
            not store in-forward checkpoints for every one it consumes.
    """
    contract = kv_pool.arena.runtime_contract
    has_state = any(spec.attn_kind == "state" for spec in contract.group_specs)
    if has_state and not attn_backend.stores_in_forward_state_checkpoints:
        raise ValueError(
            "--enable-state-checkpoint-in-forward: attention backend "
            f"{type(attn_backend).__name__} cannot store in-forward State "
            "checkpoints for every State group (supported: GDN with a "
            "checkpointing prefill kernel and a prefix granularity it divides, "
            "Qwen4-Exp PLE)"
        )


def compute_max_logical_pages_for_capture(
    spec: CacheGroupSpec,
    *,
    max_context_len: int,
    max_tokens_per_req: int = 1,
    overlap_schedule_depth: int = 0,
) -> int:
    """Return the decode CUDA Graph block-table width for one cache group.

    Decode only: a decode row describes live cache history, so a sliding group
    is bounded by its window and a state group's row is its two slots
    whatever the context. Prefill capture fabricates one extend across the
    whole extent and derives a write column per position in it, so it sizes
    its own tables -- see ``PrefillGraph._dummy_group_tables``.

    Decode admission reserves the current verify span plus one span for each
    overlapped schedule.  Include that complete reservation horizon here: a
    request close to the model context limit can still expose the reserved
    pages in its scheduler block-table row before the accepted tokens are
    truncated by the request-length limit.

    Args:
        spec: Cache group layout and kind.
        max_context_len: Maximum accepted raw-token context length.
        max_tokens_per_req: Runtime decode/verify width.
        overlap_schedule_depth: Number of additionally in-flight decode steps.

    Returns:
        Required block-table columns for one request.
    """
    if max_context_len < 0:
        raise ValueError(f"max_context_len must be >= 0, got {max_context_len}")
    if max_tokens_per_req <= 0:
        raise ValueError(f"max_tokens_per_req must be > 0, got {max_tokens_per_req}")
    if overlap_schedule_depth not in (0, 1):
        raise ValueError(
            f"overlap_schedule_depth must be 0 or 1, got {overlap_schedule_depth}"
        )
    if spec.attn_kind == "state":
        return STATE_TABLE_SLOTS
    block_granularity = spec.block_granularity
    reservation_horizon = (overlap_schedule_depth + 1) * max_tokens_per_req
    if spec.attn_kind == "sliding_window":
        # A window wider than the context retains the whole context; the extra
        # column is the block a window's first row lands in mid-block.
        retained = min(spec.sliding_window_tokens, max_context_len)
        live_tokens = retained + reservation_horizon
        return _ceil_div(live_tokens, block_granularity) + 1
    live_tokens = max_context_len + reservation_horizon
    return _ceil_div(live_tokens, block_granularity)


# Sliding sub-groups make each slab bound by one layer of every group — no dead slab rows.
_SLIDING_SUBGROUP_PREFIX = "sliding_attention_"


def _attn_kind_for_label(label: str) -> AttnKind | None:
    """Cache-group kind for a layer_type label, or None if unknown.

    Args:
        label: A layer_type label — one of the exact vocabulary in
            ``_LAYER_TYPE_ATTN_KIND``, or a sliding sub-group label
            ``sliding_attention_<k>`` (k a decimal index).

    Returns:
        The label's kind, or None for labels outside the vocabulary.
    """
    attn_kind = _LAYER_TYPE_ATTN_KIND.get(label)
    if attn_kind is not None:
        return attn_kind
    if (
        label.startswith(_SLIDING_SUBGROUP_PREFIX)
        and label[len(_SLIDING_SUBGROUP_PREFIX) :].isdigit()
    ):
        return "sliding_window"
    return None


def _is_window_int(value: object) -> bool:
    """True for a real int; a bool is never a window, however int-like it is."""
    return isinstance(value, int) and not isinstance(value, bool)


def _windows_per_layer(
    sliding_window_tokens: SlidingWindowTokens, num_layers: int
) -> tuple[list[int | None], bool]:
    """Normalize either window spelling to one entry per layer.

    Args:
        sliding_window_tokens: A scalar window to broadcast, one entry per
            layer, or None.
        num_layers: How many layers the windows must cover.

    Returns:
        ``(windows, broadcast)`` -- the per-layer windows, and whether they
        came from a scalar. Callers need that second half: a broadcast scalar
        reaches full-history layers too, which must then ignore it, while a
        window written at a full-history position in a sequence is a
        mislabeled layer.

    Raises:
        ValueError: Not a window spelling, or a sequence of the wrong length.
    """
    if sliding_window_tokens is None or _is_window_int(sliding_window_tokens):
        return [sliding_window_tokens] * num_layers, True
    if isinstance(sliding_window_tokens, str) or not isinstance(
        sliding_window_tokens, Sequence
    ):
        raise ValueError(  # noqa: TRY004 - preserve the existing API contract
            "sliding_window_tokens must be None, an int, or a sequence of "
            f"int/None, got {sliding_window_tokens!r}"
        )
    windows = list(sliding_window_tokens)
    if len(windows) != num_layers:
        raise ValueError(
            f"sliding_window_tokens has {len(windows)} entries but "
            f"layer_types has {num_layers}"
        )
    return windows, False


def hybrid_slab_group_size(
    layer_types: Sequence[str] | None,
    *,
    sliding_window_tokens: SlidingWindowTokens = None,
) -> int | None:
    """Slab count for the hybrid slab KV layout (the i-th layer of EACH
    group shares slab i), or None when the model cannot share slabs.

    This is the sizing divisor the ordinary recipe turns profiled bytes per
    token into parents with; the planned field layout pairs layers the same
    way through ``group``'s per-group occurrence counter. The scheduler's
    single BlockPool owns each page id by at most one group, so paired
    layers' live rows never overlap. Unknown labels degrade to None -- the
    predicate gates an optimization, so it must not raise.

    Groups may be unequal in size (e.g. Inkling's 55 sliding + 11 full):
    the slab count is the LARGEST group's layer count; slabs beyond a
    smaller group's count are single-layer. Equal groups keep the original
    gpt-oss pairing (count == group size). Sliding sub-group labels
    ("sliding_attention_<k>") count as separate groups — equal-count
    sub-groups make every slab fully bound (Inkling 5x11 + 11 -> 11 slabs).

    Multi-window models (a per-layer window sequence with >1 distinct
    window) degrade to None: the slab pairing is per raw label, not per
    (kind, window) group.
    """
    if not layer_types:
        return None
    counts: dict[str, int] = {}
    for label in layer_types:
        # State rows are not byte-equal with KV rows, so no slab pairing.
        if _attn_kind_for_label(label) in (None, "state"):
            return None
        counts[label] = counts.get(label, 0) + 1
    if len(counts) < 2:
        return None
    windows = sliding_window_tokens
    if windows is None or isinstance(windows, int):
        # One window for every sliding layer: pairing per raw label holds.
        return max(counts.values())
    if not isinstance(windows, Sequence) or len(windows) != len(layer_types):
        return None
    distinct = {
        window
        for label, window in zip(layer_types, windows)
        if _attn_kind_for_label(label) == "sliding_window"
        and _is_window_int(window)
        and window > 0
    }
    return None if len(distinct) > 1 else max(counts.values())


def _layer_attn_kind_windows(
    layer_types: Sequence[str],
    sliding_window_tokens: SlidingWindowTokens,
) -> list[tuple[AttnKind, int | None]]:
    """Validate the per-layer labels/windows and return (kind, window) per
    layer. A scalar window broadcasts to sliding layers; a sequence lines up
    1:1 (non-sliding positions must be None)."""
    windows, broadcast = _windows_per_layer(sliding_window_tokens, len(layer_types))
    rows: list[tuple[AttnKind, int | None]] = []
    for i, (label, raw) in enumerate(zip(layer_types, windows)):
        attn_kind = _attn_kind_for_label(label)
        if attn_kind is None:
            raise ValueError(
                f"unknown layer_type {label!r} at layer {i}; "
                f"expected one of {sorted(_LAYER_TYPE_ATTN_KIND)} or a "
                f"sliding sub-group label '{_SLIDING_SUBGROUP_PREFIX}<k>'"
            )
        if raw is not None and not _is_window_int(raw):
            raise ValueError(
                f"layer {i} ({label!r}) window must be None or an int, got {raw!r}"
            )
        if attn_kind == "sliding_window":
            if raw is None or raw <= 0:
                raise ValueError(
                    f"layer {i} ({label!r}) is sliding but its "
                    f"window is not a positive int (got {raw!r})"
                )
            rows.append((attn_kind, raw))
            continue
        # A broadcast scalar reaches non-sliding layers too and they ignore
        # it; a window written at this position by hand means the label is
        # wrong. Either way the group carries no window.
        if not broadcast and raw is not None and raw > 0:
            raise ValueError(
                f"layer {i} ({label!r}) is {attn_kind} but "
                f"carries sliding window {raw}; mislabeled layer_type?"
            )
        rows.append((attn_kind, None))
    return rows


def layer_group_ids(
    *,
    layer_types: Sequence[str],
    sliding_window_tokens: SlidingWindowTokens,
) -> list[str]:
    """Per-layer cache group id, derived once from the storage labels; the
    model side never spells these (``bind_cache_groups`` stamps each
    ``PagedAttention`` from the plan), so ``block_tables`` keys line up with
    the published group specs by construction.

    The id is the bare label unless sliding layers carry more than one
    distinct window (then ``label_<window>``), so single-window models keep
    byte-identical ids."""
    rows = _layer_attn_kind_windows(layer_types, sliding_window_tokens)
    distinct = {w for k, w in rows if k == "sliding_window"}
    multi_window = len(distinct) > 1
    return [
        (
            f"{label}_{window}"
            if multi_window and attn_kind == "sliding_window"
            else label
        )
        for label, (attn_kind, window) in zip(layer_types, rows)
    ]


def split_recurrent_state_groups(layer_types: Sequence[str]) -> list[str]:
    """Split each recurrent run by its position between history layers.

    Qwen3.5 repeats ``state-0, state-1, state-2, full``. The three state
    positions have independent physical layouts while repeated occurrences of
    one position remain one cache group.
    """
    group_ids = []
    state_position = 0
    for label in layer_types:
        if label in STATE_LAYER_TYPES:
            group_ids.append(f"{label}_{state_position}")
            state_position += 1
        else:
            group_ids.append(label)
            state_position = 0
    return group_ids


def group(
    *,
    layer_types: Sequence[str],  # len: num_layers
    group_ids: Sequence[str],  # len: num_layers
    sliding_window_tokens: SlidingWindowTokens,
    prefix_granularity: int,
    fields_for_layer,
    pd_disaggregation_enabled: bool = False,
) -> tuple[CacheGroupDeclaration, ...]:
    """Walk the layers once, building each group whole.

    A cache group has two halves -- the scheduler-facing spec and the bytes
    its fields occupy -- and one walk produces both: every layer contributes
    its kind and window to its group's spec and its fields to that same
    group's field list, keyed by the one ``group_id`` variable. There is
    no second enumeration to disagree with, so nothing needs cross-checking.

    Physical packing is deliberately absent from the specs: how many of a
    group's CacheBlocks share one LCM parent is solved by the memory plan and
    published by the arena.

    vLLM-style spec-value grouping: layers collapse into one group per
    distinct group id. Group order = first-appearance order.

    Args:
        layer_types: Per-layer labels: "full_attention" / "sliding_attention"
            (or sliding sub-group labels "sliding_attention_<k>") /
            "linear_attention" (a state group, e.g. Qwen3.5 GDN). The kind
            always comes from these labels; the recipe resolves one label
            per layer (CacheRecipe.layer_types).
        group_ids: Physical group id per layer. The cache recipe is the
            single source of these ids: derive them with ``layer_group_ids``
            for label-equivalent grouping, or supply a finer split (hybrid
            models, e.g. ``split_recurrent_state_groups``). Layers sharing a
            group id must agree on (kind, window).
        sliding_window_tokens: One window for all sliding layers (today's HF
            scalar), or a per-layer sequence (multi-window models; full-layer
            positions must be None).
        prefix_granularity: Scheduler-wide prefix granularity in tokens; every
            group's CacheBlock spans it.
        fields_for_layer: ``(layer_id, group_id, occurrence) -> fields``. The
            occurrence is how many layers of this group already declared
            fields, i.e. this layer's slot in the group's plane numbering; a
            layer that declares nothing does not consume a slot.
        pd_disaggregation_enabled: Stamp PD transfer policies on the specs.

    Returns:
        ``(spec, fields)`` pairs in first-appearance order, ready for
        ``pack``.

    Raises:
        ValueError: unknown label; window sequence length mismatch; sliding
            layer without a positive window; full layer carrying a window;
            group id shared across incompatible layer policies; a group whose
            layers declare no fields.
    """
    resolved_group_ids = tuple(group_ids)
    if not resolved_group_ids:
        raise ValueError(
            "group requires per-layer group_ids; the "
            "cache recipe is their single source: derive them with "
            "layer_group_ids(...)"
        )
    resolved_layer_types = tuple(layer_types)
    if len(resolved_group_ids) != len(resolved_layer_types):
        raise ValueError(
            f"group_ids has {len(resolved_group_ids)} entries but layer_types "
            f"has {len(resolved_layer_types)}"
        )
    layer_policies = _layer_attn_kind_windows(
        resolved_layer_types, sliding_window_tokens
    )

    specs: dict[str, CacheGroupSpec] = {}
    fields: dict[str, tuple] = {}
    occurrences: dict[str, int] = {}
    for layer_id, ((attn_kind, window), gid) in enumerate(
        zip(layer_policies, resolved_group_ids)
    ):
        if gid in specs:
            existing = specs[gid]
            if (existing.attn_kind, existing.sliding_window_tokens) != (
                attn_kind,
                window,
            ):
                raise ValueError(f"group_id {gid!r} mixes incompatible layer policies")
        else:
            specs[gid] = _layer_group_spec(
                group_id=gid,
                attn_kind=attn_kind,
                window=window,
                block_tokens=prefix_granularity,
            )

        occurrence = occurrences.get(gid, 0)
        declared = tuple(fields_for_layer(layer_id, gid, occurrence))
        if declared:
            occurrences[gid] = occurrence + 1
            fields[gid] = fields.get(gid, ()) + declared
    barren = sorted(set(specs) - set(fields))
    if barren:
        raise ValueError(
            f"cache groups {barren} declare no fields; a group with no bytes "
            "cannot be addressed"
        )
    published = specs.values()
    if pd_disaggregation_enabled:
        published = apply_pd_transfer_policies(tuple(published))
    return tuple((spec, fields[spec.group_id]) for spec in published)


def _layer_group_spec(
    *,
    group_id: str,
    attn_kind: AttnKind,
    window: int | None,
    block_tokens: int,
) -> CacheGroupSpec:
    """One group's spec in the shape its kind declares."""
    if attn_kind == "state":
        # State groups have no rows: one CacheBlock holds one recurrent state.
        return CacheGroupSpec(group_id=group_id, attn_kind=attn_kind, replayable=False)
    return CacheGroupSpec(
        group_id=group_id,
        attn_kind=attn_kind,
        rows_per_page=block_tokens,
        entry_stride_tokens=1,
        sliding_window_tokens=window,
        replayable=False,
    )


def apply_pd_transfer_policies(
    specs: Sequence[CacheGroupSpec],
) -> list[CacheGroupSpec]:
    """Stamp PD-disaggregation transfer policies onto group specs.

    State groups transfer only their trailing checkpoint; history groups -- a
    sliding window included -- transfer their complete retained suffix.
    """
    return [
        replace(
            spec,
            transfer_policy=(
                "latest_snapshot" if spec.attn_kind == "state" else "full_suffix"
            ),
        )
        for spec in specs
    ]


