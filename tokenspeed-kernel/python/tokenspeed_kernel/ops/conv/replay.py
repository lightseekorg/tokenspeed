"""Device-selected double buffering for raw convolution replay rows."""

from dataclasses import dataclass

import torch


@dataclass(frozen=True)
class BankedConvReplayPayload:
    """A payload view in bank zero and a stream-ordered device bank selector.

    ``bank_stride`` is in payload elements. ``a`` and ``b`` describe current
    gates and are not banked. Both banks must outlive every convolution read.
    """

    payload: torch.Tensor
    a: torch.Tensor
    b: torch.Tensor
    bank: torch.Tensor
    bank_stride: int
