"""Single-instruction FP32 PTX arithmetic for Triton kernels on NVIDIA."""

from tokenspeed_kernel._triton import tl, triton


@triton.jit
def mul_rn_f32(a, b):
    """``mul.rn.f32``: one multiply, never fused into an FMA or flushed."""
    return tl.inline_asm_elementwise(
        "mul.rn.f32 $0, $1, $2;",
        "=f,f,f",
        [a, b],
        dtype=tl.float32,
        is_pure=True,
        pack=1,
    )


@triton.jit
def add_rn_f32(a, b):
    """``add.rn.f32``: one add the compiler can neither reassociate nor fuse."""
    return tl.inline_asm_elementwise(
        "add.rn.f32 $0, $1, $2;",
        "=f,f,f",
        [a, b],
        dtype=tl.float32,
        is_pure=True,
        pack=1,
    )


@triton.jit
def div_rn_f32(a, b):
    """``div.rn.f32``: one correctly rounded divide."""
    return tl.inline_asm_elementwise(
        "div.rn.f32 $0, $1, $2;",
        "=f,f,f",
        [a, b],
        dtype=tl.float32,
        is_pure=True,
        pack=1,
    )


@triton.jit
def rcp_approx_ftz_f32(x):
    """``rcp.approx.ftz.f32``: the approximate, flush-to-zero reciprocal."""
    return tl.inline_asm_elementwise(
        "rcp.approx.ftz.f32 $0, $1;",
        "=f,f",
        [x],
        dtype=tl.float32,
        is_pure=True,
        pack=1,
    )
