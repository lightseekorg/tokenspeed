// Isolated fault-test provider: only registered test addresses, never DMA.
#include "wire.h"
#include <cstdlib>
#include <set>
#include <ylt/coro_rpc/coro_rpc_server.hpp>

namespace {
uint64_t next = 1;
std::set<uint64_t> held;
} // namespace
namespace mooncake {
std::vector<tl::expected<GetReplicaListResponse, ErrorCode>>
WrappedMasterService::BatchGetReplicaList(const std::vector<std::string> &keys,
                                         const std::string &) {
  std::vector<tl::expected<GetReplicaListResponse, ErrorCode>> result;
  for (const auto &key : keys) {
    LocalDiskDescriptor disk{{1, 1}, 16, "test-provider"};
    if (key == "versioned")
      disk.storage_generation = UUID{1, 2};
    Replica::Descriptor replica{1, disk, ReplicaStatus::COMPLETE};
    result.emplace_back(GetReplicaListResponse{{replica}, 60000, std::nullopt});
  }
  return result;
}
async_simple::coro::Lazy<tl::expected<BatchGetOffloadObjectResponse, ErrorCode>>
RealClient::batch_get_offload_object(const std::vector<std::string> &keys,
                                     const std::vector<int64_t> &sizes) {
  // Fixed bytes from the SDK's generation-key wire format, not generated by
  // the bridge helper under test. A wrong or absent generation must miss.
  const std::string versioned_key(
      "\0MCGEN1\x01\0\0\0\0\0\0\0\x02\0\0\0\0\0\0\0test\0versioned", 37);
  for (const auto &key : keys)
    if (key.ends_with("versioned") && key != versioned_key)
      co_return tl::unexpected(static_cast<ErrorCode>(-704));
  const auto id = next++;
  held.insert(id);
  BatchGetOffloadObjectResponse result{
      id, std::vector<uint64_t>(keys.size(), 0x100000), "test-provider", 60000};
  co_return result;
}
bool RealClient::release_offload_buffer(uint64_t id) {
  return held.erase(id) == 1;
}
} // namespace mooncake
int main(int argc, char **argv) {
  if (argc != 2)
    return 2;
  mooncake::RealClient provider;
  mooncake::WrappedMasterService master;
  coro_rpc::coro_rpc_server server(1,
                                   static_cast<uint16_t>(std::stoi(argv[1])));
  server.register_handler<&mooncake::RealClient::batch_get_offload_object,
                          &mooncake::RealClient::release_offload_buffer>(
      &provider);
  server.register_handler<&mooncake::WrappedMasterService::BatchGetReplicaList>(&master);
  return server.start() ? 1 : 0;
}
